## Возможные вопросы на защите

**Q: Что такое `WITH RECURSIVE`?**
A: Рекурсивное CTE (Common Table Expression — обобщённое табличное выражение). Запрос, который ссылается сам на себя. Состоит из двух частей: базовый случай (anchor — начальные данные) и рекурсивный случай (каждый следующий шаг на основе предыдущего), соединённые через `UNION ALL`.

**Q: Что такое `0::BIGINT`?**
A: Приведение типа (type cast — преобразование типа данных). `::` — сокращённый синтаксис PostgreSQL. `0::BIGINT` значит «число 0 типа BIGINT». Без приведения PostgreSQL использует INTEGER, который переполнится на больших числах Фибоначчи.

**Q: Почему `UNION ALL`, а не `UNION`?**
A: `UNION` удаляет дубликаты. В последовательности Фибоначчи есть два числа 1 (F(1)=1, F(2)=1). `UNION` удалит второе, и последовательность сломается. `UNION ALL` сохраняет все строки.

**Q: Когда рекурсия остановится?**
A: Когда условие `WHERE nxt < pstop` перестанет выполняться. Как только следующее число Фибоначчи достигнет или превысит `pstop`, рекурсивный случай не добавит новых строк, и цикл прекратится.

**Q: Что если передать `pstop = 0`?**
A: Возвращается пустая таблица. Базовый случай создаёт `cur=0, nxt=1`, но `SELECT cur FROM fib` вернёт 0, а 0 не меньше 0. Подожди — на самом деле вернётся одна строка `0`, потому что базовый случай выполняется всегда, а `WHERE nxt < pstop` проверяется только в рекурсивном случае.

**Q: Что если передать `pstop = 1`?**
A: Вернётся `0`. Базовый случай: `cur=0, nxt=1`. Рекурсия: `nxt(1) < pstop(1)` — ложь, стоп. Только одна строка.

**Q: Почему SQL, а не PL/pgSQL?**
A: Задание даёт выбор. SQL с рекурсивным CTE — декларативный подход: описываешь правило, PostgreSQL сам раскручивает. PL/pgSQL с циклом — императивный: пишешь каждый шаг вручную. SQL проще и PostgreSQL может оптимизировать его эффективнее.

**Q: Зачем столбец `nxt`, если в результат идёт только `cur`?**
A: `nxt` — вспомогательный столбец для вычислений. Чтобы вычислить следующее число Фибоначчи, нужно знать два предыдущих: `cur` и `nxt`. В финальный `SELECT cur FROM fib` попадает только `cur`, а `nxt` отбрасывается.