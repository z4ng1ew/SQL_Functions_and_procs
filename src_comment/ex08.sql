## Альтернативные варианты написания

**1. PL/pgSQL с циклом WHILE**

```sql
CREATE FUNCTION fnc_fibonacci(pstop INTEGER DEFAULT 10)
RETURNS TABLE (a BIGINT) AS $$
DECLARE
    cur BIGINT := 0;
    nxt BIGINT := 1;
    temp BIGINT;
BEGIN
    WHILE cur < pstop LOOP
        a := cur;
        RETURN NEXT;       -- возвращает текущую строку
        temp := cur;
        cur := nxt;
        nxt := temp + nxt;
    END LOOP;
END;
$$ LANGUAGE plpgsql;
-- Императивный подход: явный цикл с переменными.
-- Как в Си. Работает, но PostgreSQL не может оптимизировать.
```

**2. Другие имена столбцов в CTE**

```sql
WITH RECURSIVE fib(a, b) AS (
    SELECT 0::BIGINT, 1::BIGINT
    UNION ALL
    SELECT b, a + b FROM fib WHERE b < pstop
)
SELECT a FROM fib;
-- Имена a, b вместо cur, nxt.
-- Как в чеклисте. Результат тот же.
```

**3. С приведением через CAST вместо `::`**

```sql
SELECT CAST(0 AS BIGINT), CAST(1 AS BIGINT)
-- Вместо:
SELECT 0::BIGINT, 1::BIGINT
-- :: — сокращённый синтаксис PostgreSQL.
-- CAST — стандарт SQL, работает во всех СУБД.
```

**4. UNION вместо UNION ALL**

```sql
-- НЕЛЬЗЯ! Сломает последовательность:
SELECT 0::BIGINT, 1::BIGINT
UNION          -- удалит "дубликат" (1, 1)
SELECT nxt, cur + nxt FROM fib WHERE nxt < pstop
-- Числа 1, 1 — не дубликат! Это два разных числа Фибоначчи
-- (F(1)=1 и F(2)=1). UNION удалит второе, и последовательность сломается.
```

